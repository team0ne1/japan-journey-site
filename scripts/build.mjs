import { assertPublicText } from './public-journey.mjs';
import { compileJourney } from './compile-journey.mjs';
await compileJourney();
import { cp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { build } from 'esbuild';
import { runInNewContext } from 'node:vm';
// The same explicit step IDs drive browser anchors and server validation.
const itinerary = runInNewContext(`${await readFile('dist/data.js', 'utf8')}; ${await readFile('dist/journey-model.js', 'utf8')}; ({DAYS, PLAN_B, PLACES, JOURNEY_MODEL})`);
const routeContext = { window: {} };
runInNewContext(await readFile('dist/route-data.js', 'utf8'), routeContext);
const routes = routeContext.window.TripRouteData.validate(JSON.parse(await readFile('dist/routes.json', 'utf8')), itinerary.PLACES);
for (const segment of routes.segments) {
  const day = segment.plan === 'B' ? itinerary.PLAN_B[segment.day] ?? itinerary.DAYS[segment.day - 1] : itinerary.DAYS[segment.day - 1];
  const index = day.stops.findIndex(stop => stop.commentId === segment.toStep);
  if (index < 1 || day.stops[index - 1].id !== segment.from || day.stops[index].id !== segment.to)
    throw new Error('Saved route does not match itinerary order: ' + segment.toStep);
  if (segment.source === 'google-routes' && (Date.parse(segment.expiresAt) <= Date.now() || Date.parse(segment.capturedAt) > Date.now()))
    throw new Error('Remove or refresh expired Google route geometry before building: ' + segment.toStep);
}
// Every itinerary location and the optional Kamo area must ship with its photo.
const photos = runInNewContext(`${await readFile('dist/place-images.js', 'utf8')}; PLACE_IMAGES`);
// Every selectable route needs a local photo, including explicitly labeled area references.
for (const days of Object.values(itinerary.JOURNEY_MODEL.variants))
 for (const variants of Object.values(days)) for (const day of variants) for (const stop of day.stops)
  if (!photos[stop.id]) throw new Error('Missing active itinerary photo: ' + stop.id);

for (const id of new Set([...Object.keys(itinerary.PLACES), 'kamo'])) {
  const photo = photos[id];
  if (!photo && itinerary.JOURNEY_MODEL.places[id]) continue; // Missing photos use an explicit placeholder, never another place's image.
  if (!photo || !photo.alt || !photo.author || !photo.license || !photo.source?.startsWith('https://')) throw new Error('Incomplete photo metadata: ' + id);
  if (photo.kind === 'commons' && photo.license !== 'Public domain' && !photo.licenseUrl?.startsWith('https://')) throw new Error('Missing photo license: ' + id);
  for (const path of [photo.src, photo.thumbnail]) {
    if (typeof path !== 'string' || !/^photos\/(?:thumbs\/)?[a-z0-9-]+\.jpg$/.test(path)) throw new Error('Invalid local photo path: ' + id);
    const bytes = await readFile('dist/' + path);
    if (bytes.length < 100 || bytes[0] !== 0xff || bytes[1] !== 0xd8) throw new Error('Invalid JPEG photo: ' + id);
  }
}
const targets = {};
for (const [plan, days] of Object.entries(itinerary.JOURNEY_MODEL.variants)) {
 for (const variants of Object.values(days)) for (const day of variants) for (const stop of day.stops) {
  if (!/^[a-z0-9-]{1,80}$/.test(stop.commentId)) throw new Error('Invalid commentId: '+stop.commentId);
  const target={day:day.id,plan:day.id<5?'shared':plan==='B2'?'B':plan,place:itinerary.PLACES[stop.id][0],time:stop.time};
  if(targets[stop.commentId] && targets[stop.commentId].place!==target.place) throw new Error('Comment moved to another place: '+stop.commentId);
  targets[stop.commentId]??=target;
 }
}
await writeFile('src/comment-targets.ts', `// Generated by scripts/build.mjs from explicit IDs in dist/data.js.\nexport type CommentTarget = { day: number; plan: string; place: string; time: string };\nexport const COMMENT_TARGETS: Record<string, CommentTarget> = ${JSON.stringify(targets, null, 2)};\n`);
// Derive the server weather whitelist from the same dates and places as the page.
const weather = runInNewContext(`${await readFile('dist/weather-config.js', 'utf8')}; ({WEATHER_YEAR, WEATHER_CURRENT_AREAS, WEATHER_AREAS, WEATHER_AREAS_B})`);
const weatherDays = {};
for (const plan of ['A', 'B']) weatherDays[`0:${plan}`] = {
  date: null,
  locations: weather.WEATHER_CURRENT_AREAS.map(([id, name]) => {
    const place = itinerary.PLACES[id];
    if (!place || !name || !Number.isFinite(place[1]) || !Number.isFinite(place[2])) throw new Error('Invalid current weather location: ' + id);
    return { id, name, latitude: place[1], longitude: place[2] };
  })
};
for (const plan of ['A', 'B']) for (const original of itinerary.DAYS) {
  const day = plan === 'B' ? itinerary.PLAN_B[original.id] ?? original : original;
  const areas = (plan === 'B' ? weather.WEATHER_AREAS_B[day.id] : null) ?? weather.WEATHER_AREAS[day.id];
  const date = `${weather.WEATHER_YEAR}-${day.date.replace('.', '-')}`;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || new Date(date).toISOString().slice(0, 10) !== date || !areas?.length) throw new Error('Invalid weather day: ' + day.id);
  weatherDays[`${day.id}:${plan}`] = {
    date,
    locations: areas.map(([id, name]) => {
      const place = itinerary.PLACES[id];
      if (!place || !name || !Number.isFinite(place[1]) || !Number.isFinite(place[2])) throw new Error('Invalid weather location: ' + id);
      return { id, name, latitude: place[1], longitude: place[2] };
    })
  };
}
await writeFile('src/weather-days.ts', `// Generated from dist/data.js and dist/weather-config.js; do not edit directly.\nexport const WEATHER_DAYS = ${JSON.stringify(weatherDays, null, 2)};\n`);
const target = '.build/assets';
await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });
await cp('dist', target, { recursive: true });
// The migrated page no longer ships or requests the old map SDK.
await rm(`${target}/vendor`, { recursive: true, force: true });
await cp('web/auth.html', `${target}/auth.html`);
await cp('web/auth.css', `${target}/auth.css`);
await cp('web/shopping.css', `${target}/shopping.css`);
await build({ entryPoints: ['web/shopping.js'], outfile: `${target}/shopping.js`, bundle: true, minify: true, target: ['es2022'], format: 'esm' });
await cp('web/favorites.css', `${target}/favorites.css`);
await build({ entryPoints: ['web/favorites.js'], outfile: `${target}/favorites.js`, bundle: true, minify: true, target: ['es2022'], format: 'esm' });
await build({ external: ['/favorites.js','/shopping.js'], entryPoints: ['web/auth.js'], outfile: `${target}/auth.js`, bundle: true, minify: true, target: ['es2022'], format: 'esm', legalComments: 'eof' });
const html = await readFile(`${target}/index.html`, 'utf8');
await writeFile(`${target}/index.html`, html.replace('</head>', '<link rel="stylesheet" href="/auth.css"><script type="module" src="/auth.js"></script></head>'));
// Sites' platform configuration must never become a downloadable asset.
await rm(`${target}/.openai`, { recursive: true, force: true });
// The public text version is generated from the same redacted model, not private Markdown.
const publicText=['# 关西七日 · 公开行程','个人预订资料不公开。'];
for(const variants of Object.values(itinerary.JOURNEY_MODEL.variants.A)){
 const day=variants[0];publicText.push(`## Day ${day.id} · ${day.city}`,day.subtitle);
 for(const stop of day.stops)publicText.push(`### ${itinerary.PLACES[stop.id][0]}`,stop.time,stop.note,stop.connection||'');
}
await writeFile('dist/itinerary.md',publicText.join('\n\n')+'\n');
await cp('dist/itinerary.md',`${target}/itinerary.md`);
// Publish only reviewed files; documentation, backups and future accidental copies stay private.
const {readdir}=await import('node:fs/promises');
const approved=new Set(['index.html','favicon.svg','maps-terms.html','auth.html','auth.js','auth.css','favorites.js','favorites.css','shopping.js','shopping.css','app.js','data.js','estimates.js','hours.js','schedule.js','place-images.js','place-photos.js','tickets.js','weather-config.js','weather.js','journey-model.js','route-data.js','google-map.js','routes.json','google-map.css','style.css','itinerary-ui.css','weather.css','itinerary.md','hours-guide.md']);
const paths=[];
async function audit(dir,prefix=''){
 for(const file of await readdir(dir,{withFileTypes:true})){
  const path=prefix+file.name;
  if(file.isDirectory()){
   if(path==='photos'||path==='photos/thumbs')await audit(`${dir}/${file.name}`,path+'/');
   else await rm(`${dir}/${file.name}`,{recursive:true,force:true});
  }else if(approved.has(path)||/^photos\/(?:thumbs\/)?[a-z0-9-]+\.jpg$/.test(path)){
   if(!path.endsWith('.jpg'))assertPublicText(await readFile(`${dir}/${file.name}`,'utf8'));
   paths.push('/'+path);
  }else await rm(`${dir}/${file.name}`);
 }
}
await audit(target);
await writeFile('src/public-assets.ts',`// Generated from audited publication assets.\nexport const PUBLIC_ASSETS = new Set(${JSON.stringify(paths.sort())});\n`);
console.log('Built and audited public itinerary assets.');
