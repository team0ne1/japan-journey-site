import { cp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { build } from 'esbuild';
import { runInNewContext } from 'node:vm';
// The same explicit step IDs drive browser anchors and server validation.
const itinerary = runInNewContext(`${await readFile('dist/data.js', 'utf8')}; ({DAYS, PLAN_B, PLACES})`);
const targets = {};
for (const [days, plan] of [[itinerary.DAYS, 'A'], [Object.values(itinerary.PLAN_B), 'B']]) {
  for (const day of days) for (const stop of day.stops) {
    if (!/^[a-z0-9-]{1,80}$/.test(stop.commentId) || targets[stop.commentId]) throw new Error('Missing or duplicate commentId: ' + stop.commentId);
    targets[stop.commentId] = { day: day.id, plan: day.id < 6 ? 'shared' : plan, place: itinerary.PLACES[stop.id][0], time: stop.time };
  }
}
await writeFile('src/comment-targets.ts', `// Generated by scripts/build.mjs from explicit IDs in dist/data.js.\nexport type CommentTarget = { day: number; plan: string; place: string; time: string };\nexport const COMMENT_TARGETS: Record<string, CommentTarget> = ${JSON.stringify(targets, null, 2)};\n`);
const target = '.build/assets';
await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });
await cp('dist', target, { recursive: true });
await cp('web/auth.html', `${target}/auth.html`);
await cp('web/auth.css', `${target}/auth.css`);
await cp('web/comments.css', `${target}/comments.css`);
await build({ entryPoints: ['web/comments.js'], outfile: `${target}/comments.js`, bundle: true, minify: true, target: ['es2022'], format: 'esm' });
await build({ entryPoints: ['web/auth.js'], outfile: `${target}/auth.js`, bundle: true, minify: true, target: ['es2022'], format: 'esm', legalComments: 'eof' });
const html = await readFile(`${target}/index.html`, 'utf8');
await writeFile(`${target}/index.html`, html.replace('</head>', '<link rel="stylesheet" href="/auth.css"><link rel="stylesheet" href="/comments.css"><script type="module" src="/auth.js"></script><script type="module" src="/comments.js"></script></head>'));
// Sites' platform configuration must never become a downloadable asset.
await rm(`${target}/.openai`, { recursive: true, force: true });
console.log('Built Cloudflare assets; original itinerary content retained.');
